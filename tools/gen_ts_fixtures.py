#!/usr/bin/env python3
"""Emit a compile-time + runtime smoke module from valid fixtures.

The emitted TypeScript calls a generic ``encode<T extends keyof Schemas>`` for
every fixture. ``tsc`` therefore structurally checks each JSON fixture against
the *generated* TypeScript type, and running the emitted JavaScript performs a
JSON encode/decode round-trip. This is intentionally not a source-text grep.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path, PurePosixPath
from typing import Any, Sequence


_COMPONENT_RE = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")


def _component_name(schema_ref: str) -> str:
    if not isinstance(schema_ref, str) or schema_ref.count("#") != 1:
        raise ValueError(f"invalid schema_ref {schema_ref!r}")
    path_part, fragment = schema_ref.split("#", 1)
    if path_part == "openapi.yaml":
        prefix = "/components/schemas/"
        if not fragment.startswith(prefix):
            raise ValueError(f"invalid OpenAPI schema_ref {schema_ref!r}")
        component = fragment[len(prefix) :]
    else:
        pure = PurePosixPath(path_part)
        if pure.is_absolute() or len(pure.parts) != 1 or pure.suffix != ".json":
            raise ValueError(f"invalid schema_ref file {schema_ref!r}")
        if not fragment.startswith("/") or fragment.count("/") != 1:
            raise ValueError(f"schema_ref must target '#/<Component>': {schema_ref!r}")
        component = fragment[1:]
    if not _COMPONENT_RE.fullmatch(component):
        raise ValueError(f"invalid component name in {schema_ref!r}")
    return component


def collect(contracts_root: Path) -> list[tuple[str, Any, str]]:
    examples_dir = contracts_root / "examples"
    if not examples_dir.is_dir():
        raise SystemExit(f"gen_ts_fixtures: missing fixture directory {examples_dir}")
    records: list[tuple[str, Any, str]] = []
    files = sorted(examples_dir.glob("*.json"))
    if not files:
        raise SystemExit(f"gen_ts_fixtures: no fixture JSON in {examples_dir}")
    for path in files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(payload, list):
            raise SystemExit(f"gen_ts_fixtures: {path} must contain a JSON array")
        for index, record in enumerate(payload):
            if not isinstance(record, dict):
                raise SystemExit(f"gen_ts_fixtures: {path}[{index}] is not an object")
            if record.get("valid") is not True:
                continue
            if "value" not in record or "schema_ref" not in record:
                raise SystemExit(
                    f"gen_ts_fixtures: {path}[{index}] needs schema_ref and value"
                )
            component = _component_name(record["schema_ref"])
            description = str(record.get("description", ""))
            records.append((component, record["value"], description))
    return records


def render(records: Sequence[tuple[str, Any, str]]) -> str:
    lines = [
        "// Generated by tools/gen_ts_fixtures.py from contracts/examples/*.json.",
        "// Do not edit. tsc type-checks each fixture against the generated types,",
        'declare const console: { log(message: string): void };',
        'import type { components } from "../koishi/contracts/types.gen";',
        "",
        "type Schemas = components[\"schemas\"];",
        "",
        "function encode<T extends keyof Schemas>(name: T, value: Schemas[T]): void {",
        "  const encoded = JSON.stringify(value);",
        "  const decoded = JSON.parse(encoded) as Schemas[T];",
        "  const reencoded = JSON.stringify(decoded);",
        "  if (reencoded !== encoded) {",
        "    throw new Error(`contract fixture round-trip mismatch: ${String(name)}`);",
        "  }",
        "}",
        "",
    ]
    for component, value, description in records:
        literal = json.dumps(value, ensure_ascii=True, indent=2, sort_keys=False)
        lines.append(f"// {description}".rstrip())
        lines.append(f'encode("{component}", {literal});')
        lines.append("")
    lines.append(
        f'console.log("contract fixture encode/decode OK: {len(records)} record(s)");',
    )
    lines.append("")
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("contracts", nargs="?", default="contracts")
    parser.add_argument("output", nargs="?", default="build/ts-fixtures.gen.ts")
    args = parser.parse_args(argv)

    try:
        records = collect(Path(args.contracts))
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"gen_ts_fixtures: {exc}", file=sys.stderr)
        return 1
    if not records:
        print("gen_ts_fixtures: no valid fixtures found", file=sys.stderr)
        return 1

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(records), encoding="utf-8")
    print(f"gen_ts_fixtures: wrote {len(records)} fixture(s) to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
